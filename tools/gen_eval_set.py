# ---------------------------------------------------------------- 装配

def _empty_note(rule_id, category):
    return f"规则{rule_id}·{category}"


def build():
    """把语料装配成 samples 列表。id 按生成顺序分配，全量确定后即冻结。"""
    samples = []
    seq = 0

    def add(query, relevant, category, tags, note):
        nonlocal seq
        seq += 1
        if note is None:
            note = _empty_note(relevant[0], category) if relevant else f"超纲·{category}"
        samples.append({
            "id": f"q{seq:03d}",
            "query": query,
            "relevant": relevant,
            "category": category,
            "tags": tags,
            "hardReview": category in ("negation", "cross") or "conflict" in tags,
            "note": note,
        })

    for rule_id, rows in DIRECT.items():
        for row in rows:
            query, extra = row[0], row[1]
            note = row[2] if len(row) > 2 else None
            add(query, [rule_id], "direct", list(extra), note)

    for rule_id, rows in COLLOQUIAL.items():
        for row in rows:
            query, extra = row[0], row[1]
            note = row[2] if len(row) > 2 else None
            add(query, [rule_id], "colloquial", ["colloquial"] + list(extra), note)

    for rule_id, rows in TYPO.items():
        for row in rows:
            query, extra = row[0], row[1]
            note = row[2] if len(row) > 2 else None
            add(query, [rule_id], "typo", ["typo"] + list(extra), note)

    for rule_id, rows in NEGATION.items():
        for row in rows:
            query, extra = row[0], row[1]
            note = row[2] if len(row) > 2 else None
            add(query, [rule_id], "negation", ["negation"] + list(extra), note)

    for row in CROSS:
        query, relevant, note = row[0], row[1], row[2]
        add(query, relevant, "cross", ["multi_rule"], note)

    for row in OUT_OF_SCOPE:
        query, near_miss, note = row[0], row[1], row[2]
        add(query, [], "out_of_scope", ["near_miss"] if near_miss else [], note)

    return samples


# ---------------------------------------------------------------- 校验

def validate(samples):
    errs = []
    seen_ids, seen_queries = set(), defaultdict(list)

    for s in samples:
        sid = s["id"]
        if sid in seen_ids:
            errs.append(f"{sid}: id 重复")
        seen_ids.add(sid)
        seen_queries[s["query"]].append(sid)

        bad_tags = set(s["tags"]) - set(TAG_VOCAB)
        if bad_tags:
            errs.append(f"{sid}: tags 越界 {bad_tags}")
        if len(set(s["tags"])) != len(s["tags"]):
            errs.append(f"{sid}: tags 有重复项")

        if s["category"] == "out_of_scope":
            if s["relevant"]:
                errs.append(f"{sid}: 超纲题 relevant 必须为空")
        else:
            if not s["relevant"]:
                errs.append(f"{sid}: 非超纲题 relevant 不能为空")
            for r in s["relevant"]:
                if r not in RULES_INDEX:
                    errs.append(f"{sid}: relevant {r} 不在 rulesIndex 内")
            if len(set(s["relevant"])) != len(s["relevant"]):
                errs.append(f"{sid}: relevant 有重复项")

        want_hr = s["category"] in ("negation", "cross") or "conflict" in s["tags"]
        if s["hardReview"] != want_hr:
            errs.append(f"{sid}: hardReview 不变式违反（标 {s['hardReview']}，应为 {want_hr}）")

    for q, ids in seen_queries.items():
        if len(ids) > 1:
            errs.append(f"query 重复：『{q}』出现在 {ids}")

    # 标签最小样本数（防细粒度噪音标签复活）
    tag_count = Counter(t for s in samples for t in s["tags"])
    for tag, n in tag_count.items():
        if n < MIN_TAG_SAMPLES:
            errs.append(f"标签 '{tag}' 仅 {n} 条（< {MIN_TAG_SAMPLES}），应合并或删除")

    # direct 必须覆盖全部 19 条规则
    covered = {r for s in samples if s["category"] == "direct" for r in s["relevant"]}
    if samples and any(s["category"] == "direct" for s in samples):
        missing = set(RULES_INDEX) - covered
        if missing:
            errs.append(f"direct 未覆盖规则 {sorted(missing)}")

    return errs, tag_count


# ---------------------------------------------------------------- 报告

def report(samples, errs, tag_count):
    by_cat = Counter(s["category"] for s in samples)
    done = [c for c in QUOTA if by_cat.get(c, 0) >= QUOTA[c]]
    todo = [c for c in QUOTA if c not in done]

    print("=" * 68)
    print(f"样本总数：{len(samples)} / 500")
    print("-" * 68)
    print("类别分布（实得 / 配额）：")
    for c in QUOTA:
        n = by_cat.get(c, 0)
        mark = "OK " if n >= QUOTA[c] else ("-- " if n == 0 else "!! ")
        print(f"  {mark}{c:<13} {n:>4} / {QUOTA[c]}")
    print("-" * 68)
    print("标签频次直方图：")
    if tag_count:
        mx = max(tag_count.values())
        for tag, n in tag_count.most_common():
            bar = "#" * max(1, round(n / mx * 32))
            print(f"  {tag:<11} {n:>4}  {bar}")
    else:
        print("  （无）")
    print("-" * 68)
    hr = sum(1 for s in samples if s["hardReview"])
    print(f"人工精查子集：{hr} / {HARD_REVIEW_QUOTA['_total']}")
    print(f"已完成类别：{done or '无'}")
    print(f"待生成类别：{todo or '无'}")
    print("=" * 68)
    if errs:
        print(f"校验失败（{len(errs)} 项）：")
        for e in errs:
            print(f"  ✗ {e}")
    else:
        print("校验通过：无错误")
    print("=" * 68)


def print_samples(samples, n):
    """分层抽样：按规则轮转取，保证覆盖的规则数最大化。

    纯随机抽样在 19 条规则的池子里抽 10 条，实测会全撞在一两条规则上
    （首轮 q201/q203/q206/q209 四条都是规则 37），人工抽检等于没抽。
    """
    if not samples:
        return
    n = min(n, len(samples))

    buckets = defaultdict(list)
    for s in samples:
        buckets[s["relevant"][0] if s["relevant"] else 0].append(s)
    for v in buckets.values():
        random.Random(SAMPLE_SEED).shuffle(v)

    picked, rule_ids = [], sorted(buckets)
    while len(picked) < n:
        progressed = False
        for r in rule_ids:                      # 每轮从各规则各取一条
            if buckets[r] and len(picked) < n:
                picked.append(buckets[r].pop())
                progressed = True
        if not progressed:
            break
    picked.sort(key=lambda s: s["id"])
    covered = len({s["relevant"][0] for s in picked if s["relevant"]})
    print(f"\n人工抽检 {n} 条（分层抽样 seed={SAMPLE_SEED}，覆盖 {covered} 条规则，固定可复现）：")
    print("-" * 68)
    for s in picked:
        tags = ",".join(s["tags"]) or "-"
        hr = "★精查" if s["hardReview"] else "     "
        print(f"{s['id']} {hr} [{s['category']}/{tags}]")
        print(f"   Q: {s['query']}")
        print(f"   A: {s['relevant'] or '（不召回）'}")
        print(f"   note: {s['note']}")
    print("-" * 68)


